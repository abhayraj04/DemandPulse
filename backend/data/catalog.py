# File path for runtime editable price persistence
CONFIG_DIR = Path(__file__).parent.parent.parent / "data" / "processed"
PRICES_OVERRIDE_FILE = CONFIG_DIR / "configured_prices.json"

# In-memory working copies
_PRODUCT_MAP: Dict[str, Dict[str, Any]] = {}
_ITEM_TO_PRODUCT: Dict[int, Dict[str, Any]] = {}


def _init_catalog():
    """Initializes product registry and applies any saved demo price overrides."""
    global _PRODUCT_MAP, _ITEM_TO_PRODUCT
    _PRODUCT_MAP.clear()
    _ITEM_TO_PRODUCT.clear()

    # Load persistent price overrides if available
    price_overrides: Dict[str, float] = {}
    if PRICES_OVERRIDE_FILE.exists():
        try:
            with open(PRICES_OVERRIDE_FILE, "r", encoding="utf-8") as f:
                price_overrides = json.load(f)
        except Exception:
            price_overrides = {}

    for prod in RAW_100_PRODUCTS:
        p_id = prod["product_id"]
        p_copy = dict(prod)

        # Apply price override if configured
        if p_id in price_overrides:
            override_price = float(price_overrides[p_id])
            ratio = override_price / p_copy["configured_price_inr"] if p_copy["configured_price_inr"] > 0 else 1.0
            p_copy["configured_price_inr"] = override_price
            p_copy["unit_cost_inr"] = round(p_copy["unit_cost_inr"] * ratio, 2)

        # Calculated margin percent
        price = p_copy["configured_price_inr"]
        cost = p_copy["unit_cost_inr"]
        margin_pct = round(((price - cost) / price) * 100, 1) if price > 0 else 0.0
        p_copy["margin_pct"] = margin_pct
        p_copy["sku"] = p_id
        # Aliases for compatibility
        p_copy["unit_price"] = price
        p_copy["unit_cost"] = cost
        p_copy["lead_time_days"] = 7
        p_copy["moq"] = 100

        _PRODUCT_MAP[p_id] = p_copy
        if p_copy["item_id"] is not None:
            _ITEM_TO_PRODUCT[p_copy["item_id"]] = p_copy


_init_catalog()


