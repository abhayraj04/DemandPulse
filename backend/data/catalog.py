def get_product(item_id: int) -> Dict[str, Any]:
    """Retrieves product mapped to Kaggle numerical item_id (1..50)."""
    if item_id in _ITEM_TO_PRODUCT:
        return _ITEM_TO_PRODUCT[item_id]

    # Fallback for unknown item_id
    p_id = f"P{item_id:03d}"
    return {
        "product_id": p_id,
        "item_id": item_id,
        "name": f"Indian Retail Product {item_id}",
        "brand": "Generic Brand",
        "category": "General Staples",
        "package_size": "Standard Pack",
        "configured_price_inr": 100.0,
        "unit_cost_inr": 75.0,
        "margin_pct": 25.0,
        "unit_price": 100.0,
        "unit_cost": 75.0,
        "lead_time_days": 7,
        "moq": 100,
        "supplier": "Retail Supply Partner",
        "sku": p_id,
        "forecast_availability": "Available" if item_id <= 50 else "Catalog Only",
    }


def get_all_products(category: Optional[str] = None, forecast_only: bool = False) -> List[Dict[str, Any]]:
    """Returns list of all 100 Indian retail products, with optional filtering."""
    prods = list(_PRODUCT_MAP.values())
    if category:
        prods = [p for p in prods if p["category"].lower() == category.lower()]
    if forecast_only:
        prods = [p for p in prods if p["forecast_availability"] == "Available"]
    return prods


def update_product_price(product_id: str, new_price_inr: float) -> Optional[Dict[str, Any]]:
    """Updates a configured demonstration price for a product. Persists to disk."""
    if product_id not in _PRODUCT_MAP:
        return None

    if new_price_inr <= 0:
        raise ValueError("Configured demo price must be positive.")

    prod = _PRODUCT_MAP[product_id]
    old_price = prod["configured_price_inr"]
    prod["configured_price_inr"] = round(new_price_inr, 2)
    prod["unit_price"] = prod["configured_price_inr"]

    # Proportionally adjust cost to maintain realistic gross margin
    if old_price > 0:
        ratio = new_price_inr / old_price
        prod["unit_cost_inr"] = round(prod["unit_cost_inr"] * ratio, 2)
        prod["unit_cost"] = prod["unit_cost_inr"]

    price = prod["configured_price_inr"]
    cost = prod["unit_cost_inr"]
    prod["margin_pct"] = round(((price - cost) / price) * 100, 1) if price > 0 else 0.0

    # Also update item map if linked
    if prod["item_id"] is not None and prod["item_id"] in _ITEM_TO_PRODUCT:
        _ITEM_TO_PRODUCT[prod["item_id"]] = prod

    # Save to JSON
    try:
        CONFIG_DIR.mkdir(parents=True, exist_ok=True)
        overrides = {}
        if PRICES_OVERRIDE_FILE.exists():
            with open(PRICES_OVERRIDE_FILE, "r", encoding="utf-8") as f:
                overrides = json.load(f)
        overrides[product_id] = prod["configured_price_inr"]
        with open(PRICES_OVERRIDE_FILE, "w", encoding="utf-8") as f:
            json.dump(overrides, f, indent=2)
    except Exception as e:
        print(f"Warning: Failed to persist configured price to disk: {e}")

    return prod


